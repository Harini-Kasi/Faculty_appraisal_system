-- 5 = Professional / Excellent
-- 4 = Proficient / Very Good
-- 3 = Specialist / Good
-- 2 = Practitioner / Satisfactory
-- 1 = Need improvement / Low (WF)
--
-- Final Faculty Performance Index:
-- FPI = 0.50 * SA + 0.30 * RBA + 0.10 * HPE + 0.10 * SF
--
-- Source-specific threshold data:
-- KPI5 Impact Factor: >1.5 | 1.0-1.5 | 0.5-1 | 0.25-0.5 | 0.1-0.25
-- KPI7 Worth of projects: >10 Lakhs | 7.5-10 Lakhs | 5-7.5 Lakhs | 2.5-5.0 Lakhs | Below 2.5 Lakhs
-- KPI14 Academic Results: 95-100% | 90-95% | 85-90% | 80-85% | 75-80%
-- E1 Student feedback: 90-100% | 80-90% | 70-80% | 60-70% | 50-60%
