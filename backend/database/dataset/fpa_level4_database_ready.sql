CREATE DATABASE IF NOT EXISTS fpa_level4;
USE fpa_level4;

DROP TABLE IF EXISTS performance_levels;
DROP TABLE IF EXISTS criteria;
DROP TABLE IF EXISTS sections;

CREATE TABLE sections (
    section_id INT PRIMARY KEY,
    section_code VARCHAR(20) NOT NULL UNIQUE,
    section_name VARCHAR(255) NOT NULL,
    description TEXT
);

CREATE TABLE criteria (
    criterion_id INT PRIMARY KEY,
    section_id INT NOT NULL,
    criterion_code VARCHAR(20) NOT NULL UNIQUE,
    criterion_name VARCHAR(500) NOT NULL,
    weight DECIMAL(6,2),
    FOREIGN KEY (section_id) REFERENCES sections(section_id)
);

CREATE TABLE performance_levels (
    performance_id INT AUTO_INCREMENT PRIMARY KEY,
    criterion_id INT NOT NULL,
    level_no TINYINT NOT NULL,
    level_name VARCHAR(100) NOT NULL,
    description TEXT NOT NULL,
    UNIQUE (criterion_id, level_no),
    FOREIGN KEY (criterion_id) REFERENCES criteria(criterion_id)
);

